#!/usr/bin/env python3
"""Render the Demo's rounded-rectangle SVG into a compact indexed PNG."""

from io import BytesIO
from pathlib import Path
from xml.etree import ElementTree

from PIL import Image, ImageDraw


APP = Path(__file__).resolve().parents[1]
SIZE = 180
SUPERSAMPLE = 4
SVG = "{http://www.w3.org/2000/svg}"


def render_png():
    svg = ElementTree.parse(APP / "assets/rt-carplay-oem.svg").getroot()
    origin_x, origin_y, width, height = map(float, svg.attrib["viewBox"].split())
    if (origin_x, origin_y) != (0, 0) or width != height:
        raise ValueError("Expected a square SVG with a zero origin")

    scale = SIZE * SUPERSAMPLE / width
    image = Image.new("RGBA", (SIZE * SUPERSAMPLE, SIZE * SUPERSAMPLE))
    draw = ImageDraw.Draw(image)
    for element in svg:
        if element.tag in (SVG + "title", SVG + "desc"):
            continue
        if element.tag != SVG + "rect":
            raise ValueError("The OEM SVG must use only rounded rectangles")
        x, y, w, h, radius = (
            round(float(element.attrib[key]) * scale) for key in ("x", "y", "width", "height", "rx")
        )
        draw.rounded_rectangle((x, y, x + w - 1, y + h - 1), radius, fill=element.attrib["fill"])

    image = image.resize((SIZE, SIZE), Image.Resampling.BOX)
    image = image.quantize(colors=16, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    encoded = BytesIO()
    image.save(encoded, format="PNG", optimize=True, bits=4)
    return encoded.getvalue()


def main():
    png = render_png()
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in png[offset:offset + 12]) + ","
        for offset in range(0, len(png), 12)
    ]
    header = [
        "/* Generated by tools/generate_oem_icon.py from assets/rt-carplay-oem.svg. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define CARPLAY_DEMO_OEM_ICON_SIZE {SIZE}U",
        "static const uint8_t carplay_demo_oem_icon_png[] = {",
        *rows,
        "};",
        "",
    ]
    (APP / "assets/rt-carplay-oem-png.h").write_bytes("\n".join(header).encode("ascii"))


if __name__ == "__main__":
    main()
