"""Generate the V4 icon masks from the official Lucide icon font.

The design package (docs/FONT_ICON_GUIDE.md) names Lucide as the icon source
and asks for single-colour SVGs converted to A8 assets instead of hand-drawn
primitives. This script renders the named glyphs with Pillow, scales each one
to the exact pixel size the pages place, and writes LVGL A8 image descriptors.
Only the generated C/H files are checked in: firmware builds never need the
font, Pillow or Node.js.

Usage:
  python3 tools/generate_icon_assets.py <lucide-static@0.468.0/font/lucide.ttf>

The Lucide font draws its icons in the same 24x24 viewBox as the design SVGs,
so at size N an icon occupies the N x N box anchored at the placement the
design uses (`icon(s,name,x,y,N)` in the design's build.py). Each glyph is
drawn over the whole em square with the ascender at the top, which reproduces
the SVG `transform="translate(x y) scale(N/24)"` placement exactly.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# (C name, Lucide icon, codepoint, pixel size). One entry per placement.
ICONS = (
    ("arrow_left_22", "arrow-left", 0xE04C, 22),
    ("arrow_left_20", "arrow-left", 0xE04C, 20),
    ("smartphone_24", "smartphone", 0xE166, 24),
    ("smartphone_42", "smartphone", 0xE166, 42),
    ("settings_24", "settings", 0xE157, 24),
    ("link_24", "link", 0xE107, 24),
    ("volume_29", "volume-2", 0xE1AA, 29),
    ("sun_29", "sun", 0xE17B, 29),
    ("download_26", "download", 0xE0B6, 26),
    ("download_39", "download", 0xE0B6, 39),
    ("refresh_24", "refresh-cw", 0xE148, 24),
    ("chevron_right_23", "chevron-right", 0xE073, 23),
    ("ellipsis_25", "ellipsis", 0xE0BA, 25),
    ("info_26", "info", 0xE0FE, 26),
    ("languages_24", "languages", 0xE103, 24),
    ("map_pin_24", "map-pin", 0xE114, 24),
)

SUPERSAMPLE = 8
DESTINATION = Path(__file__).resolve().parents[1] / "ui/icons"
NOTICE = (
    "/* Generated by tools/generate_icon_assets.py; do not edit.\n"
    " * Lucide icons (https://lucide.dev), ISC license; see icons/LICENSE.\n"
    " * Single-colour 8-bit alpha masks (A8), recoloured by the theme role.\n"
    " * Do not edit: regenerate instead of hand-patching the bitmaps. */\n"
)


def render(font: ImageFont.FreeTypeFont, codepoint: int, size: int) -> bytes:
    """Renders one glyph over the whole em square, like the design's SVG scale."""
    high = size * SUPERSAMPLE
    # The Lucide font's ascent equals its em size and its icons are drawn in the
    # same 24x24 viewBox as the design SVGs. Drawing at `high` px with the
    # ascender at y = 0 therefore maps viewBox (0,0)-(24,24) onto this canvas,
    # exactly the SVG's translate(x y) scale(size/24) placement.
    image = Image.new("L", (high, high), 0)
    ImageDraw.Draw(image).text((0, 0), chr(codepoint), font=font, fill=255)
    if image.getbbox() is None:
        raise SystemExit("glyph U+%04X rendered empty" % codepoint)

    data = image.resize((size, size), Image.Resampling.LANCZOS).tobytes()
    if not any(data):
        raise SystemExit("glyph U+%04X empty after scaling to %dpx" %
                         (codepoint, size))
    return data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("font", type=Path, help="lucide.ttf (lucide-static package)")
    args = parser.parse_args()

    DESTINATION.mkdir(parents=True, exist_ok=True)
    source = [NOTICE, '#include "lvgl.h"', ""]
    header = ["/* Generated by tools/generate_icon_assets.py; do not edit. */",
              "#pragma once",
              '#include "lvgl.h"',
              ""]

    for name, icon, codepoint, size in ICONS:
        font = ImageFont.truetype(str(args.font), size * SUPERSAMPLE)
        data = render(font, codepoint, size)
        source.append("/* Lucide %s, %dpx */" % (icon, size))
        source.append("static const uint8_t carplay_icon_%s_map[] = {" % name)
        for offset in range(0, len(data), 16):
            source.append("    " + " ".join("0x%02x," % byte
                                            for byte in data[offset:offset + 16]))
        source.append("};")
        source.append("const lv_image_dsc_t carplay_icon_%s = {" % name)
        source.append("    .header.magic = LV_IMAGE_HEADER_MAGIC,")
        source.append("    .header.cf = LV_COLOR_FORMAT_A8,")
        source.append("    .header.w = %d," % size)
        source.append("    .header.h = %d," % size)
        source.append("    .header.stride = %d," % size)
        source.append("    .data_size = sizeof(carplay_icon_%s_map)," % name)
        source.append("    .data = carplay_icon_%s_map," % name)
        source.append("};")
        source.append("")

        header.append("/* Lucide %s, %dpx */" % (icon, size))
        header.append("extern const lv_image_dsc_t carplay_icon_%s;" % name)
        print("carplay_icon_%-20s %2dpx %5d bytes" % (name, size, len(data)))

    (DESTINATION / "carplay_icons.c").write_text("\n".join(source), encoding="utf-8")
    (DESTINATION / "carplay_icons.h").write_text("\n".join(header) + "\n",
                                                encoding="utf-8")


if __name__ == "__main__":
    main()
