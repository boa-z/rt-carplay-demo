"""Generate the launcher's OFL font subsets (fontTools + lv_font_conv 1.5.3).

Every size is generated from the same symbol set: the label table in
ui/ui_language.c plus any non-ASCII literal in ui/*.c. ui_language.c switches a
label to the CJK face sized for it, so a size that lacked glyphs would render
boxes only at that size."""
import argparse
from itertools import groupby
from pathlib import Path
import re
import subprocess
import tempfile

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SIZES = (16, 18, 24, 30)

parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path, help="NotoSansSC[wght].ttf, SIL OFL 1.1")
parser.add_argument("converter", type=Path, help="lv_font_conv.js 1.5.3")
parser.add_argument("--full", action="store_true", help="Generate the complete dynamic-text face instead of UI subsets")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
source = (root / "ui/ui_language.c").read_text(encoding="utf-8")
symbols = {c for c in source if ord(c) > 127}
for extra in (root / "ui").glob("*.c"):
    if extra == root / "ui/ui_language.c":
        continue
    for literal in re.findall(r'"([^"\n]*)"', extra.read_text(encoding="utf-8")):
        symbols.update(c for c in literal if ord(c) > 127)
symbols = "".join(sorted(symbols))
destination = root / "ui/fonts"
destination.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory() as temp:
    font = TTFont(args.font)
    regular = instantiateVariableFont(font, {"wght": 400}, inplace=True)
    path = Path(temp) / "CarPlayUI-Regular.ttf"
    regular.save(path)
    if args.full:
        ranges = []
        codepoints = sorted(cp for cp in regular.getBestCmap() if cp >= 0x20)
        for _, block in groupby(enumerate(codepoints), lambda item: item[1] - item[0]):
            points = [cp for _, cp in block]
            ranges.append(hex(points[0]) if len(points) == 1 else "{}-{}".format(hex(points[0]), hex(points[-1])))
        output = destination / "carplay_cjk_full_18.c"
        subprocess.run([
            "node", str(args.converter), "--font", str(path), "--size", "18",
            "--bpp", "2", "--range", ",".join(ranges), "--no-kerning",
            "--format", "lvgl", "--lv-font-name", output.stem, "-o", str(output),
        ], check=True)
        text = output.read_text(encoding="utf-8")
        text = text[text.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
        notice = ("/* Generated by tools/generate_ui_fonts.py --full; do not edit.\n"
                  " * Noto Sans SC, weight 400, 18px, 2bpp; {} mapped characters.\n"
                  " * Copyright 2014-2021 Adobe; SIL OFL 1.1 (OFL.txt).\n"
                  " * Font renamed CarPlay UI; see README.md. */\n").format(len(codepoints))
        output.write_text(notice + text.rstrip() + "\n", encoding="utf-8")
        print(output.name, output.stat().st_size)
    for size in (() if args.full else SIZES):
        name = "carplay_cjk_{}".format(size)
        output = destination / (name + ".c")
        subprocess.run([
            "node", str(args.converter), "--font", str(path), "--size", str(size),
            "--bpp", "4", "--range", "0x20-0x7e", "--symbols", symbols,
            "--no-compress", "--no-kerning", "--format", "lvgl",
            "--lv-fallback", "lv_font_montserrat_16", "--lv-font-name", name,
            "-o", str(output),
        ], check=True)
        text = output.read_text(encoding="utf-8")
        # Replace the generated machine-specific command with provenance.
        text = text[text.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
        notice = ("/* Generated by tools/generate_ui_fonts.py; do not edit.\n"
                  " * Noto Sans SC, weight 400, {}px, 4bpp.\n"
                  " * Copyright 2014-2021 Adobe; SIL OFL 1.1 (OFL.txt).\n"
                  " * Font subset renamed CarPlay UI; see README.md. */\n").format(size)
        output.write_text(notice + text, encoding="utf-8")
        print(output.name, output.stat().st_size)
