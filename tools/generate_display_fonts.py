"""Generate the Inter subsets used by the native LVGL pages.

The variable font is instantiated at the design weights, then converted with the
pinned lv_font_conv 1.5.3. Large numerals contain digits and units only; the
small text subsets contain printable ASCII. Chinese comes from the Noto subsets
generated by generate_ui_fonts.py."""
import argparse
from pathlib import Path
import subprocess
import tempfile

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

NUMERALS = "0123456789.%:-/"
# Printable ASCII actually present in the V4 English label set and values.
TEXT = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
        "0123456789 .,:;!?()[]/+-%'\"")

# (output name, pixel size, weight, CJK fallback size or zero). The large numeral
# subsets use 2 bpp: at 58 px and above the quantization is not visible, while
# 4 bpp would cost about a megabyte of flash for the two dashboard faces.
FONTS = (
    ("carplay_display_220", 220, 600, 0),
    ("carplay_display_110", 110, 600, 0),
    ("carplay_display_115", 115, 600, 0),
    ("carplay_display_58", 58, 600, 0),
    ("carplay_ui_34", 34, 600, 30),
    ("carplay_ui_21", 21, 600, 24),
    ("carplay_ui_18", 18, 600, 18),
    ("carplay_ui_17", 17, 500, 18),
    ("carplay_ui_15", 15, 500, 16),
    ("carplay_ui_14", 14, 400, 16),
)

parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path, help="Inter[opsz,wght].ttf, SIL OFL 1.1")
parser.add_argument("converter", type=Path, help="lv_font_conv.js 1.5.3")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
destination = root / "ui/fonts"
destination.mkdir(exist_ok=True)

with tempfile.TemporaryDirectory() as temp:
    instances = {}
    for name, size, weight, fallback_size in FONTS:
        digits = not fallback_size
        fallback = "lv_font_montserrat_16" if digits else "carplay_cjk_{}".format(fallback_size)
        if weight not in instances:
            font = TTFont(args.font)
            axes = {"wght": weight}
            if "opsz" in [axis.axisTag for axis in font["fvar"].axes]:
                axes["opsz"] = 32
            path = Path(temp) / "Inter-{}.ttf".format(weight)
            instantiateVariableFont(font, axes, inplace=True).save(path)
            instances[weight] = path
        output = destination / (name + ".c")
        glyphs = ["--symbols", NUMERALS if digits else TEXT]
        subprocess.run([
            "node", str(args.converter), "--font", str(instances[weight]),
            "--size", str(size), "--bpp", "2" if digits else "4", *glyphs,
            "--no-compress", "--no-kerning", "--format", "lvgl",
            "--lv-fallback", fallback, "--lv-font-name", name,
            "-o", str(output),
        ], check=True)
        text = output.read_text(encoding="utf-8")
        # Replace the generated machine-specific command with provenance.
        text = text[text.index("#ifdef LV_LVGL_H_INCLUDE_SIMPLE"):]
        notice = ("/* Generated by tools/generate_display_fonts.py; do not edit.\n"
                  " * Inter, weight {weight}, {size}px, 4bpp.\n"
                  " * Copyright 2016 The Inter Project Authors; SIL OFL 1.1 (OFL.txt).\n"
                  " * Font subset renamed {name}; see README.md. */\n")
        output.write_text(notice.format(weight=weight, size=size, name=name) + text, encoding="utf-8")
        print(output.name, output.stat().st_size)
